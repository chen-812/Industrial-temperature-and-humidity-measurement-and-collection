void PCAP01_Init()
{
	uint32_t SRAMRead_value=0;

    uint32_t timeout=0;
    uint32_t i;


    do{  // 循环检测,确保系统启动
        PCAP01_Command(0x88);
        delay_ms(20);
        PCAP01_Wirte_SRAM(0x01f,0x1f);
        SRAMRead_value=PCAP01_Read_SRAM(0x01f);   // 读取系统的值
        delay_ms(50);
        timeout++;
     }while( (SRAMRead_value!=0x1f) && (timeout<0xff));


	if( (timeout>=0xff))
    {
        return;
    }
	else
	{
		PCAP01_Command(0x88);
		delay_ms(20);
		for(i=0;i<960;i++)  // previous : 928,  now is 960
		{
			PCAP01_Wirte_SRAM(i,Firmware_data[i]);  // 更新dsp的算法部分
		}
		PCAP01_Write_Register();
		delay_ms(20);
		PCAP01_Command(0x8a);
		delay_ms(20);
		PCAP01_Command(0x8c);
		delay_ms(20);

	}

}



uint32_t Read_Register(unsigned char address)
{
    uint32_t result_data=0;
    SSN_LOW;   // 拉低CS片选，让PCAP01AD进入SPI通信状态
      delay_us(10);

    Send_data[0]=0x40^address;
    Send_data[1]=0xff;
    Send_data[2]=0xff;
    Send_data[3]=0xff;
    Send_data[4]=0xff;

    CAP_SPI_TransmitReceive(Send_data,Read_data,4);

    result_data |=Read_data[1];
    result_data=result_data<<8;
    result_data |=Read_data[2];
    result_data=result_data<<8;
    result_data |=Read_data[3];

    SSN_HIGH;  // 拉高CS，结束本次通信
    delay_us(10);
    printf("Read Reg 0x%02X: 0x%08lX\r\n", address, result_data);
    return result_data;

}


//电容线性拟合
float C_a=1.0825;
float C_b=-5.516;

unsigned char no_signal_flag_h=0;

float PCAP01_result(CHANNEL channel)
{
    float result_c;
	unsigned long status_register=0;
	unsigned long result_register=0;

	status_register=Read_Register(0x08);    //读状态寄存器

	printf("STATUS: %08lX\r\n", status_register); // 新加这句
	if((status_register!=0x100000)&&(status_register!=0x900000))
	{
	    no_signal_flag_h=1;
	    return 0;
	}
	else
	{
        result_register=Read_Register(channel);
        result_c=(float)result_register/2097152*CAP0_VALUE;

        if(IF_POLY_FIT)
        {
            if((result_c*C_a+C_b)<0)
            {
                no_signal_flag_h=1;
                return 0;
            }
            else
            {
                no_signal_flag_h=0;
                return result_c*C_a+C_b;
            }
        }
        else
        {
            no_signal_flag_h=0;
            return result_c;
        }
	}
}



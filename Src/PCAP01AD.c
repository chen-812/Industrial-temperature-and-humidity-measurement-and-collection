void PCAP01_Command(unsigned char value)
{
	Send_data[0]=value;  //
	SSPI_SendData(SDCOMD);
}

/*

fun name :SSPI_SendData

input:
          size  发送数据大小：操作码

return : 返回状态
*/

void SSPI_SendData(unsigned char size)
{
	CAP_SPI_Transmit(Send_data,size);
}


void PCAP01_Wirte_SRAM(unsigned short address,unsigned char value)
{
	Send_data[0]=WSRAM<<4^(unsigned char)(address>>8);
	Send_data[1]=(unsigned char)(address&0x00ff);
	Send_data[2]=value;
	SSPI_SendData(SDFIRMWR);
}


unsigned char PCAP01_Read_SRAM(unsigned short address)
{

	Send_data[0]=RSRAM<<4^(unsigned char)(address>>8);
	Send_data[1]=(unsigned char)(address & 0x00ff);
	Send_data[2]=0xff;
	delay_ms(10);

	CAP_SPI_TransmitReceive(Send_data,Read_data,3);

	delay_ms(10);

	return (Read_data[2]);
}

void Send_RegisterData(unsigned char address,unsigned long value)
{
	Send_data[0]=0xC0^address;
	Send_data[1]=(unsigned char)(value>>16);
	Send_data[2]=(unsigned char)((value>>8)&0x000000ff);
	Send_data[3]=(unsigned char)(value&0x000000ff);
	SSPI_SendData(SDREGISTWR);
}



